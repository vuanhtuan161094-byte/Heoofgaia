"""Real offline Chrome acceptance for Fame-ranked AP and hero progression.

Chrome opens the generated game via file://. A controlled Fame/Tavern fixture skips
long progression; candidates are still generated by the live engine and hired through
the game's real delegated DOM event handler. The captured PNG is the browser output.
"""
from pathlib import Path
import base64
import html
import json
import os
import re
import shutil
import subprocess
import uuid

ROOT = Path(__file__).parent
GAME = ROOT / "Play-Heoofgaia-HG11.html"
EVIDENCE = ROOT / "docs" / "evidence" / "hg08" / "fame-ap-progression-chrome.png"
REPORT = ROOT / "docs" / "qa" / "hg08" / "fame-ap-progression-chrome.json"

INJECT = r'''<script>
window.addEventListener('load',()=>setTimeout(()=>{
 const checks=[],exceptions=[];const check=(name,ok,detail='')=>checks.push({name,ok:!!ok,detail});
 const finish=()=>{
  const result={pass:exceptions.length===0&&checks.every(x=>x.ok),checks,exceptions,
   fixture:'Fresh Human game; Fame is advanced to 2,200, AP is restored by one controlled in-game hour, Tavern is set to level 2, and hires use live DOM controls.'};
  const pre=document.createElement('pre');pre.id='hg08-hero-cap-qa-result';pre.textContent=JSON.stringify(result);document.body.appendChild(pre);
  document.title='HG08_HERO_CAP_'+(result.pass?'PASS':'FAIL');
  console.error('HG08_HERO_CAP_RESULT_B64 '+btoa(unescape(encodeURIComponent(JSON.stringify(result)))));
 };
 try{
  document.querySelector('[data-action="race"][data-race="human"]').click();
  document.querySelector('[data-action="start"]').click();
  const state=HOG_APP_DEBUG.getState();
  state.fame=2200;state.buildings.tavern=2;HOG_ENGINE.ensure08(state);HOG_ENGINE.refreshTavern(state);HOG_APP_DEBUG.render();
  const apStats=HOG_ENGINE.fameApStats(state.fame),apTag=[...document.querySelectorAll('.vitals .tag')].find(tag=>tag.textContent.includes('AP '));
  check('Fame 2,200 resolves to 200 AP maximum and 20 AP/hour',apStats.max===200&&apStats.perHour===20,JSON.stringify(apStats));
  check('HUD displays the source-based AP cap and hourly recovery',state.apMax===200&&apTag?.textContent.includes('/200 · +20/giờ'),apTag?.outerHTML||'missing AP badge');
  state.ap=0;state.speed=1;const now=Date.now();state.lastTick=now-3600000;HOG_ENGINE.tick(state,now);HOG_APP_DEBUG.render();
  check('A real one-hour game tick grants exactly 20 AP at Fame 2,200',state.ap===20&&state.apMax===200,JSON.stringify({ap:state.ap,apMax:state.apMax}));
  const restoredApTag=[...document.querySelectorAll('.vitals .tag')].find(tag=>tag.textContent.includes('AP '));
  check('Updated HUD reflects the earned AP after the gameplay tick',restoredApTag?.textContent.includes('20/200 · +20/giờ'),restoredApTag?.textContent||'missing AP badge');
  document.querySelector('[data-action="tab"][data-tab="heroes"]').click();
  check('Game hero screen displays the source-based 1/3 roster cap',document.querySelector('#main')?.innerText.includes('1/3'),document.querySelector('#main')?.innerText.match(/\d+\/\d+/)?.[0]||'missing');
  const startGold=state.res.gold;
  let hire=document.querySelector('.tavern-offers [data-action="hirecandidate"]');
  check('First live Tavern candidate is recruitable below cap',!!hire&&!hire.disabled,hire?.outerHTML||'missing');
  if(hire&&!hire.disabled)hire.click();
  check('First real hire changes hero roster, offer list and gold once',state.heroes.length===2&&state.tavern.offers.length===2&&state.res.gold<startGold,JSON.stringify({heroes:state.heroes.length,offers:state.tavern.offers.length,goldSpent:startGold-state.res.gold}));
  hire=document.querySelector('.tavern-offers [data-action="hirecandidate"]');
  if(hire&&!hire.disabled)hire.click();
  check('Second live hire reaches the fame cap',state.heroes.length===3&&state.heroes.length===HOG_ENGINE.heroCountLimit(state.fame),`${state.heroes.length}/${HOG_ENGINE.heroCountLimit(state.fame)}`);
  const remaining=[...document.querySelectorAll('.tavern-offers [data-action="hirecandidate"]')];
  check('At cap, remaining candidate control is disabled',remaining.length===1&&remaining[0].disabled,remaining.map(x=>x.outerHTML).join('\n'));
  check('Legacy Save key remains unchanged',HOG_ENGINE.SAVE_KEY==='heoofgaia_hg_only_v07',HOG_ENGINE.SAVE_KEY);
  window.scrollTo(0,0);
 }catch(e){exceptions.push(String(e?.stack||e));}
 finish();
},3000));
</script>'''


def main():
    if not GAME.is_file():
        raise SystemExit(f"Offline game not found: {GAME}")
    chrome = next((Path(os.environ.get(key, "")) / suffix for key, suffix in [
        ("PROGRAMFILES", Path("Google/Chrome/Application/chrome.exe")),
        ("PROGRAMFILES(X86)", Path("Google/Chrome/Application/chrome.exe")),
    ] if (Path(os.environ.get(key, "")) / suffix).is_file()), None)
    if chrome is None:
        raise SystemExit("Google Chrome installation was not found.")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    EVIDENCE.parent.mkdir(parents=True, exist_ok=True)
    runtime_root = REPORT.parent / "chrome-hero-cap-runtime"
    runtime_root.mkdir(parents=True, exist_ok=True)
    if not runtime_root.resolve().is_relative_to(ROOT.resolve()):
        raise RuntimeError(f"Refusing to use runtime path outside repository: {runtime_root}")
    runtime = runtime_root / uuid.uuid4().hex
    runtime.mkdir(parents=True, exist_ok=True)
    try:
        test_file = runtime / "game-qa.html"
        test_file.write_text(GAME.read_text(encoding="utf-8").replace("</body>", INJECT + "</body>"), encoding="utf-8")
        profile = runtime / "profile"
        command = [str(chrome), "--headless=new", "--no-sandbox", "--disable-gpu", "--disable-gpu-sandbox",
                   "--no-first-run", "--no-default-browser-check", "--disable-features=Vulkan", "--disable-sync",
                   "--disable-default-apps", "--disable-component-update", "--disable-background-networking",
                   "--disable-extensions", "--hide-scrollbars", "--window-size=1440,1000", "--force-device-scale-factor=1",
                   "--virtual-time-budget=12000", "--user-data-dir=" + str(profile), "--screenshot=" + str(EVIDENCE),
                   "--dump-dom", test_file.as_uri()]
        proc = subprocess.run(command, capture_output=True, timeout=60)
        output = proc.stdout.decode("utf-8", errors="replace") + "\n" + proc.stderr.decode("utf-8", errors="replace")
        found = re.search(r"HG08_HERO_CAP_RESULT_B64\s+([A-Za-z0-9+/]+={0,2})", output)
        if found:
            result = json.loads(base64.b64decode(found.group(1)).decode("utf-8"))
        else:
            dom = re.search(r'<pre id="hg08-hero-cap-qa-result">(.*?)</pre>', output, re.S)
            if not dom:
                raise RuntimeError(f"Chrome emitted no HG-08 hero-cap report; exit={proc.returncode}; tail={output[-3000:]}")
            result = json.loads(html.unescape(dom.group(1)))
        if proc.returncode != 0:
            raise RuntimeError(f"Chrome exited {proc.returncode}: {output[-2000:]}")
        report = {"browser": "Google Chrome headless CLI on the generated standalone file:// HTML",
                  "gameBuild": str(GAME.relative_to(ROOT)).replace("\\", "/"),
                  "screenshot": str(EVIDENCE.relative_to(ROOT)).replace("\\", "/"), **result}
        REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({"report": str(REPORT), "screenshot": str(EVIDENCE), "passed": sum(x["ok"] for x in result["checks"]),
                          "failed": sum(not x["ok"] for x in result["checks"]), "checks": result["checks"]}, ensure_ascii=True, indent=2))
        if not result["pass"]:
            raise SystemExit(1)
    finally:
        if runtime.resolve().is_relative_to(runtime_root.resolve()) and runtime != runtime_root:
            shutil.rmtree(runtime)


if __name__ == "__main__":
    main()
